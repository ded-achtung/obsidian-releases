#!/usr/bin/env python3
"""Причинное рассуждение: видеть vs делать, контрфактика, планирование (лестница Пёрла).

Малая структурная модель «поливалки»: Сезон → Дождь, Сезон → Поливалка,
(Дождь, Поливалка) → Мокрая трава → Скользко. На ней система делает то, чего не
может статистика: различает корреляцию и причинность, отвечает на «что если» для
конкретного случая и планирует, вмешиваясь в настоящую причину.

Запуск: python run_causal.py
"""

from __future__ import annotations

from thinking_system.reasoning.causal import SCM


def sprinkler() -> SCM:
    m = SCM()
    m.root("Сезон", {0: 0.5, 1: 0.5})                              # 0=сухой, 1=влажный
    m.eq("Дождь", ["Сезон"], lambda p: p["Сезон"])                # влажный сезон → дождь
    m.eq("Поливалка", ["Сезон"], lambda p: 1 - p["Сезон"])        # сухой сезон → включают поливалку
    m.eq("Мокро", ["Дождь", "Поливалка"], lambda p: int(p["Дождь"] or p["Поливалка"]))
    m.eq("Скользко", ["Мокро"], lambda p: p["Мокро"])
    return m


def main():
    m = sprinkler()
    print("▶ Причинная модель «поливалки»: Сезон→Дождь, Сезон→Поливалка, (Дождь|Поливалка)→Мокро→Скользко\n")

    print("1) КОРРЕЛЯЦИЯ ≠ ПРИЧИННОСТЬ (Дождь и Поливалка связаны через общий Сезон):")
    print(f"   ВИДЕТЬ: P(Поливалка=1|Дождь=1) − P(·|Дождь=0) = {m.correlation('Дождь', 'Поливалка'):+.2f}  → сильно связаны")
    print(f"   ДЕЛАТЬ: P(Поливалка=1|do Дождь=1) − P(·|do Дождь=0) = {m.affects('Дождь', 'Поливалка'):+.2f}  → причинно НЕ влияет")
    print("   Увидеть дождь — узнать про поливалку (общий сезон); ВКЛЮЧИТЬ дождь — поливалку не трогает.")

    print("\n2) ВМЕШАТЕЛЬСТВО (поливалка — настоящая причина скользкости):")
    print(f"   P(Скользко=1 | do Поливалка=1) = {m.prob('Скользко', 1, do={'Поливалка': 1}):.2f}")
    print(f"   P(Скользко=1 | do Поливалка=0) = {m.prob('Скользко', 1, do={'Поливалка': 0}):.2f}  (всё равно бывает дождь)")
    print(f"   причинный эффект Поливалка→Скользко = {m.affects('Поливалка', 'Скользко'):+.2f}")

    print("\n3) КОНТРФАКТИКА — про КОНКРЕТНЫЙ наблюдённый случай:")
    dry = {"Сезон": 0, "Поливалка": 1, "Дождь": 0, "Мокро": 1, "Скользко": 1}
    print(f"   сухой день (поливалка вкл, дождя нет, мокро): будь поливалка ВЫКЛ → Мокро = {m.counterfactual(dry, {'Поливалка': 0}, 'Мокро')}")
    wet = {"Сезон": 1, "Поливалка": 0, "Дождь": 1, "Мокро": 1, "Скользко": 1}
    print(f"   влажный день (был дождь):                     будь поливалка ВКЛ → Мокро = {m.counterfactual(wet, {'Поливалка': 1}, 'Мокро')}")
    print("   В сухой день поливалка БЫЛА причиной; в дождь — нет (дождь и так намочил).")

    print("\n4) ПЛАНИРОВАНИЕ (цель: Скользко=1 — во что вмешаться?):")
    (var, val), p = m.plan("Скользко", 1, [("Поливалка", 1), ("Дождь", 1), ("Сезон", 1), ("Сезон", 0)])
    print(f"   лучшее вмешательство: do({var}={val}) → P(Скользко=1) = {p:.2f}")

    print("\n── Итог ──")
    print("   С причинной моделью система различает «видеть» и «делать», отвечает на «что")
    print("   было бы» для конкретного случая и планирует через настоящую причину. Это")
    print("   рассуждение поверх структуры (приоры), а не корреляции из данных.")


if __name__ == "__main__":
    main()
