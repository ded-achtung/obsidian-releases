#!/usr/bin/env python3
"""Тест системы: 5 задач по алгебре + 5 по Python — индукцией правил из примеров.

Честная рамка: система НЕ читает условие на естественном языке (она не LLM). Ей
дают 2-3 примера вход→выход, она СИНТЕЗИРУЕТ программу (поиском в языке операций) и
применяет к НОВОМУ входу. Алгебра — числовые функции; Python — программы над данными
(синтезированная программа исполняется). Проверяем обобщение на отложенный вход.

Запуск: python run_benchmark.py
"""

from __future__ import annotations

from thinking_system.reasoning.induction import default_library

# (название, обучающие примеры, отложенный вход→ожидаемый выход)
ALGEBRA = [
    ("f(x) = 2x + 1",     [(3, 7), (5, 11)],                (10, 21)),
    ("f(x) = x²",         [(3, 9), (4, 16)],                (7, 49)),
    ("f(x) = (x + 1)²",   [(2, 9), (3, 16)],                (5, 36)),
    ("f(x) = 4x²",        [(2, 16), (3, 36)],               (4, 64)),
    ("f(x) = 3x − 2",     [(2, 4), (4, 10), (5, 13)],       (6, 16)),
]
# для Python-задач — эквивалентный код (синтезированное правило ему соответствует)
PYTHON = [
    ("развернуть список",        [([1, 2, 3], [3, 2, 1]), ([4, 5], [5, 4])],      ([7, 8, 9], [9, 8, 7]), "lst[::-1]"),
    ("сумма элементов",          [([1, 2, 3], 6), ([4, 5], 9)],                   ([10, 20], 30),        "sum(lst)"),
    ("максимум",                 [([3, 1, 2], 3), ([5, 9, 2], 9)],                ([8, 1], 8),           "max(lst)"),
    ("сумма удвоенных",          [([1, 2, 3], 12), ([5], 10)],                    ([10], 20),            "sum(x*2 for x in lst)"),
    ("сортировка по убыванию",   [([3, 1, 2], [3, 2, 1]), ([5, 9, 2], [9, 5, 2])],([2, 8, 4], [8, 4, 2]),"sorted(lst, reverse=True)"),
]


def solve(train, test_in):
    prog = default_library().induce(train, max_depth=3)
    return prog, (prog(test_in) if prog else None)


def main():
    print("▶ Тест системы индукцией правил: 5 алгебра + 5 Python (по 2-3 примера на задачу)\n")
    score = 0

    print("══ АЛГЕБРА ══")
    for name, train, (ti, to) in ALGEBRA:
        prog, got = solve(train, ti)
        ok = got == to
        score += ok
        print(f"  {name:<16} → правило «{prog}»")
        print(f"     проверка: {ti} → {got}  (ожидалось {to})  {'✓' if ok else '✗'}")

    print("\n══ PYTHON (синтезированная программа = код) ══")
    for name, train, (ti, to), py in PYTHON:
        prog, got = solve(train, ti)
        ok = got == to
        score += ok
        print(f"  {name:<22} → правило «{prog}»  ≡  {py}")
        print(f"     проверка: {ti} → {got}  (ожидалось {to})  {'✓' if ok else '✗'}")

    print(f"\n══ ИТОГ: {score}/10 ══")

    # честно — границы: проверяем на ОТЛОЖЕННОМ входе (а не только на обучающих)
    print("\nЧестно о границах (проверка на новом входе ловит мнимые правила):")
    for name, train, (ti, to) in [("f(x) = x³", [(2, 8), (3, 27)], (4, 64)),
                                  ("f(x) = x² + x", [(2, 6), (3, 12)], (4, 20))]:
        prog, got = solve(train, ti)
        if prog is None:
            print(f"  {name:<14}: не выведено — нужного примитива нет в языке")
        elif got != to:
            print(f"  {name:<14}: вывело «{prog}», но на {ti} даёт {got}≠{to} — совпало на примерах, не правило")
        else:
            print(f"  {name:<14}: «{prog}» — решено")

    print("\n── Что это значит ──")
    print("   Система РЕШИЛА задачи, выведя правило из 2-3 примеров и обобщив на новый вход —")
    print("   без корпуса, поиском в языке операций. Это синтез программ, а не понимание")
    print("   условия на языке: дать примеры она может, прочитать текст задачи — нет (это LLM).")


if __name__ == "__main__":
    main()
