"""Честный замер ПОКРЫТИЯ системы: решает ли она задачу, ОБОБЩАЯ на отложенный вход.

Принцип (без утечки): правило выводится из train-примеров и проверяется на ОТДЕЛЬНОМ
held-out входе, который НЕ участвовал в индукции. Задача засчитана только если на
held-out ответ верный — это меряет обобщение, а не запоминание примеров.

Плюс НЕГАТИВНЫЕ контроли: задачи ВНЕ шаблонов (экспонента, произвольные точки,
произвольная сетка). На них система не должна выдавать правило, верно обобщающее на
held-out — иначе это «угадала» совпадением. Так замер сам себя проверяет на честность.

Набор самодостаточен (данные в репозитории) и воспроизводим из кода — ровно то, чего
не хватало раньше, когда «замер на ARC» нельзя было воспроизвести.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any, Callable

from thinking_system.reasoning.invention import _morph
from thinking_system.system import ThinkingSystem


@dataclass
class Task:
    name: str
    category: str
    train: list[tuple]
    test_in: Any
    test_out: Any
    in_scope: bool = True


def _eq(a: Any, b: Any) -> bool:
    try:
        return type(a) == type(b) and a == b
    except (TypeError, ValueError):
        return False


# Сетки для grid-задач (кортежи кортежей — то, что принимают grid-операции)
_G = ((0, 0, 0), (0, 5, 0), (0, 0, 0))
_H = ((0, 0), (3, 0))
_GT = ((0, 5, 0, 0),)
_E = ((5, 5, 5), (5, 0, 5), (5, 5, 5))


def suite() -> list[Task]:
    """Самодостаточный набор задач с отложенным входом + негативные контроли."""
    return [
        # ── арифметика (функции из наблюдений) ──
        Task("аффинная 3x+5", "арифметика", [(2, 11), (4, 17), (5, 20)], 10, 35),
        Task("квадратичная x²+x", "арифметика", [(2, 6), (3, 12), (4, 20), (5, 30)], 6, 42),
        # ── списки: поэлементные / структурные / оконные ──
        Task("поэлементно ×2", "списки", [([1, 2, 3], [2, 4, 6]), ([5], [10])], [10], [20]),
        Task("циклический сдвиг", "структура", [([1, 2, 3], [2, 3, 1]), ([4, 5, 6, 7], [5, 6, 7, 4])], [9, 8], [8, 9]),
        Task("период ×2", "структура", [([1, 2], [1, 2, 1, 2]), ([3, 4, 5], [3, 4, 5, 3, 4, 5])], [7], [7, 7]),
        Task("разности соседей", "окно", [([1, 3, 6, 10], [2, 3, 4]), ([2, 5, 9], [3, 4])], [10, 12, 20], [2, 8]),
        Task("префикс-сумма", "окно", [([1, 2, 3], [1, 3, 6]), ([4, 5], [4, 9])], [2, 2, 2, 2], [2, 4, 6, 8]),
        # ── условие / ветвление ──
        Task("модуль (abs)", "условие", [(-3, 3), (-2, 2), (-5, 5), (1, 1), (4, 4), (6, 6)], -7, 7),
        Task("обнулить отрицательные", "условие", [(-3, 0), (-2, 0), (-5, 0), (1, 1), (4, 4), (6, 6)], -9, 0),
        Task("знак числа (3 ветви)", "многоветочное", [(-3, -1), (-2, -1), (5, 1), (7, 1), (0, 0)], -9, -1),
        Task("развернуть длинные", "вложенное",
             [([1, 2], [1, 2]), ([2, 1], [2, 1]), ([1, 2, 3], [3, 2, 1]),
              ([3, 2, 1], [1, 2, 3]), ([2, 4, 6, 8], [8, 6, 4, 2]), ([1, 3], [1, 3])], [5, 6, 7], [7, 6, 5]),
        # ── деревья решений (глубокая вложенность) ──
        Task("ограничение [0,10]", "дерево",
             [(-5, 0), (-2, 0), (3, 3), (7, 7), (8, 8), (9, 9), (11, 10), (15, 10)], 25, 10),
        Task("4 региона (ступень)", "дерево",
             [(-3, -1), (-1, -1), (0, 0), (2, 1), (5, 1), (6, 2), (9, 2)], 7, 2),
        # ── сетки: композиция / перекраска / морфология ──
        Task("сетка: flip_h", "сетка", [(((1, 2), (3, 4)), ((2, 1), (4, 3))),
                                         (((5, 6), (7, 8)), ((6, 5), (8, 7)))], ((9, 0), (1, 2)), ((0, 9), (2, 1))),
        Task("сетка: перекраска 1↔2", "сетка", [(((1, 2, 1),), ((2, 1, 2),)),
                                                 (((2, 2, 1),), ((1, 1, 2),))], ((1, 1, 2, 2),), ((2, 2, 1, 1),)),
        Task("сетка: дилатация", "сетка", [(_G, _morph(_G, max, False)), (_H, _morph(_H, max, False))],
             _GT, _morph(_GT, max, False)),
        Task("сетка: эрозия", "сетка", [(_E, _morph(_E, min, False)), (((5, 5), (5, 0)), _morph(((5, 5), (5, 0)), min, False))],
             ((0, 5, 5),), _morph(((0, 5, 5),), min, False)),

        # ── НЕГАТИВНЫЕ контроли: ВНЕ шаблонов → не должно «обобщить» ──
        Task("[neg] экспонента 2^x", "негатив", [(0, 1), (1, 2), (2, 4), (3, 8)], 4, 16, in_scope=False),
        Task("[neg] куб x³ из 2 точек", "негатив", [(2, 8), (3, 27)], 4, 64, in_scope=False),
        Task("[neg] произвольные числа", "негатив", [(1, 5), (2, 9), (3, 2), (4, 7)], 5, 13, in_scope=False),
        Task("[neg] произвольная сетка", "негатив",
             [(((1, 2), (3, 4)), ((9, 9), (9, 9))), (((1, 1), (1, 1)), ((2, 2), (2, 2)))],
             ((1, 2), (3, 4)), ((9, 9), (9, 9)), in_scope=False),
        Task("[neg] несвязный список", "негатив", [([1, 2, 3], [7, 7]), ([4, 5], [8])], [6, 7], [9], in_scope=False),
    ]


def evaluate(make_system: Callable[[], Any] | None = None) -> dict:
    """Прогнать набор: на каждой задаче вывести правило из train и проверить на held-out.

    Свежая система на каждую задачу — меряем ЧИСТОЕ обобщение индукции, без переноса
    выученного между задачами (это отдельная способность).
    """
    make = make_system or ThinkingSystem
    rows = []
    for t in suite():
        prog = make().solve(t.train)
        got: Any = None
        if prog is not None:
            try:
                got = prog(t.test_in)
            except Exception:  # noqa: BLE001 — правило неприменимо к held-out входу
                got = None
        solved = prog is not None and _eq(got, t.test_out)
        rows.append({"task": t, "program": str(prog) if prog is not None else None, "solved": solved})

    in_rows = [r for r in rows if r["task"].in_scope]
    neg_rows = [r for r in rows if not r["task"].in_scope]
    return {
        "rows": rows,
        "in_scope_total": len(in_rows),
        "in_scope_solved": sum(r["solved"] for r in in_rows),
        "negative_total": len(neg_rows),
        "negative_spurious": sum(r["solved"] for r in neg_rows),  # должно быть 0 (не выдумала обобщение)
    }
