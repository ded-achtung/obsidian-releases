"""Лёгкая морфология: привести формы слова к общей ОСНОВЕ (без корпуса, по правилам).

Чтобы понимать менее «причёсанный» текст, разные формы одного слова должны
узнаваться как одно: «переверни / перевернуть / перевернул» → одна основа. Это
правило-ориентированный стеммер (упрощённый Snowball для русского): снимает
частые окончания, сохраняя основу длиной ≥ 3. Приоры — морфология, а не данные;
обобщает на невиданные формы.

Честно: обрабатывает СЛОВОИЗМЕНЕНИЕ (падежи/числа/лица), но не словообразование и
не видовые пары (ворочать/вернуть) — для них нужен словарь.
"""

from __future__ import annotations

# окончания (длинные раньше): глагольные, прилагательные, существительные
_ENDINGS = sorted({
    "ться", "тесь", "ишься", "аешь", "уешь",
    "нуть", "уть", "ють", "ать", "ять", "еть", "ить", "ыть",
    "ешь", "ишь", "ете", "ите", "ают", "яют", "уют", "еют",
    "ыми", "ими", "ого", "его", "ому", "ему",
    "ами", "ями", "ах", "ях", "ов", "ев",
    "нул", "ул", "ил", "ал", "ял", "ел", "ыл",                # прошедшее: снять с гласной
    "ая", "яя", "ое", "ее", "ие", "ые", "ый", "ий", "ой", "ом", "ем", "ых", "их", "ую", "юю",
    "ат", "ят", "ут", "ют", "ит", "ет", "им", "ем", "ла", "ло", "ли", "на", "но", "ны",
    "ть", "ти", "л", "н", "а", "я", "у", "ю", "ы", "и", "е", "о", "й",
}, key=len, reverse=True)

_MIN_STEM = 3


def stem(word: str) -> str:
    """Снять самое длинное знакомое окончание, сохранив основу ≥ 3 символов."""
    w = word.lower()
    for e in _ENDINGS:
        if w.endswith(e) and len(w) - len(e) >= _MIN_STEM:
            return w[: -len(e)]
    return w


def normalize(text: str) -> list[str]:
    """Список основ слов текста (кириллица/латиница)."""
    import re

    return [stem(t) for t in re.findall(r"[а-яёa-z]+", text.lower())]
