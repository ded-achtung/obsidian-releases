#!/usr/bin/env python3
"""Замкнутый исследовательский круг: прочитать → вывести → проверить → найти пробел → дочитать.

Прочитав материал, система не ждёт вопросов, а сама ВЫВОДИТ новое знание, ПРОВЕРЯЕТ
гипотезы (свойства операций — исполнением; причины — по модели), НАХОДИТ пробелы
(явления без объяснённой причины) и, дочитав ответ, ПЕРЕОТКРЫВАЕТ следствия. Цикл
замыкается и открывается снова — система умнеет, читая и обдумывая.

Запуск: python run_research.py
"""

from __future__ import annotations

from thinking_system.language.reader import LessonReader
from thinking_system.agent.researcher import Researcher


def main():
    print("▶ Исследовательский круг над прочитанным знанием\n")
    reader = LessonReader()
    reader.read_file("books/sample_lesson.md")
    sci = Researcher(reader)

    print("1) ВЫВЕЛ НОВОЕ ЗНАНИЕ (следует из прочитанного, но НЕ было сказано):")
    for rel, a, b in sci.derive_new_facts():
        print(f"   {a} → {b}  ({rel})")

    print("\n2) ПРОВЕРИЛ ГИПОТЕЗЫ О ОПЕРАЦИЯХ исполнением (свойства, найденные сам):")
    for w, prop in sci.operation_properties([[1, 2, 3], [4, 5, 6], [7, 8]]).items():
        print(f"   «{w}»: {prop}")

    print("\n3) РАЗОБРАЛ ПРИЧИННУЮ СТРУКТУРУ:")
    cf = sci.causal_findings()
    print(f"   причинно влияет: {', '.join(f'{a}→{b}' for a, b in cf['causes'])}")
    print(f"   связаны, но НЕ причина (общий предок): {', '.join(f'{a}~{b}' for a, b in cf['correlated_not_causal'])}")
    print(f"   ОТКРЫТЫЕ ВОПРОСЫ (явления без причины): {sci.open_questions()}")

    print("\n4) ЗАМКНУЛ ЦИКЛ — дочитал ответ на свой вопрос:")
    sci.learn_more("облака вызывают дождь")
    print("   узнал: «облака вызывают дождь»")
    print(f"   вывел НОВОЕ: «облака вызывают скользкий?» → {reader.ask_causal('облака вызывают скользкий?')} "
          f"(цепочка облака→дождь→мокрый→скользкий)")
    print(f"   и поднял СЛЕДУЮЩИЙ вопрос: {sci.open_questions()}")

    print("\n── Что это значит ──")
    print("   Прочитав материал, система САМА вывела новое, проверила гипотезы, нашла пробелы")
    print("   и, узнав ответ, переоткрыла следствия и подняла новый вопрос. Это замкнутый")
    print("   круг исследования: разбор→вывод→проверка→пробел→интеграция — рассуждение над")
    print("   прочитанным, а не генерация. Чем больше читает и думает — тем способнее.")


if __name__ == "__main__":
    main()
