#!/usr/bin/env python3
"""Понимание задачи: язык → смысл → исполнение (думать и писать, не генерировать).

Система УЧИТ смысл слова из показа (видит употребление → ИНДУЦИРУЕТ операцию →
связывает слово), затем ПОНИМАЕТ новые предложения: разбирает в программу и
ИСПОЛНЯЕТ, выдавая истинный ответ. Обобщает смысл слова на новые входы и КОМПОНУЕТ
известные слова в невиданные предложения — признаки настоящего понимания.

Запуск: python run_understand.py
"""

from __future__ import annotations

from thinking_system.language.understanding import GroundedLexicon


def main():
    print("▶ Мост «язык → смысл»: система учит значения слов из показа и ИСПОЛНЯЕТ\n")
    lex = GroundedLexicon()

    print("1) УЧИТ СМЫСЛ ИЗ ПОКАЗА (никто не говорит «слово = операция» — она ВЫВОДИТ это):")
    demos = {
        "разверни":   [([1, 2, 3], [3, 2, 1]), ([4, 5], [5, 4])],
        "сложи":      [([1, 2, 3], 6), ([4, 5], 9)],
        "удвой":      [([1, 2, 3], [2, 4, 6]), ([5, 1], [10, 2])],
        "отсортируй": [([3, 1, 2], [1, 2, 3]), ([5, 9, 2], [2, 5, 9])],
        "максимум":   [([3, 1, 2], 3), ([5, 9, 2], 9)],
    }
    for w, ex in demos.items():
        lex.learn(w, ex)
        print(f"   из {len(ex)} показов «{w}» → выведена операция «{lex.words[w]}»")

    print("\n2) ПОНИМАЕТ новые предложения с НОВЫМИ входами (обобщение смысла слова):")
    for s in ["разверни [7,8,9]", "максимум [8,1]", "отсортируй [4,2,9,1]"]:
        r = lex.solve(s)
        print(f"   «{s:<22}» → {r['answer']}   (понял как: {r['reasoning']})")

    print("\n3) КОМПОНУЕТ известные слова в НЕВИДАННЫЕ предложения (системность понимания):")
    for s in ["удвой и сложи [1,2,3]", "разверни и сложи [1,2,3]"]:
        r = lex.solve(s)
        print(f"   «{s:<24}» → {r['answer']}   (понял как: {r['reasoning']})")

    print("\n4) УЧИТ НОВОЕ СЛОВО из одного показа и сразу пользуется им:")
    w = lex.learn_from_demo("переверни [1,2,3]", [1, 2, 3], [3, 2, 1])
    r = lex.solve("переверни [9,9,1]")
    print(f"   показали «переверни» → выучил операцию «{lex.words[w]}»; теперь «переверни [9,9,1]» → {r['answer']}")

    print("\n5) ЧЕСТНО про незнакомое (генератор выдумал бы — понимание признаёт незнание):")
    r = lex.solve("заверни [5,6]")
    print(f"   «заверни [5,6]» → не понял слово(а): {r['unknown']}")

    print("\n── Что это значит ──")
    print("   Смысл слова ВЫУЧЕН ИЗ УПОТРЕБЛЕНИЯ (показ → индукция операции → связь), заземлён")
    print("   в исполнении (система УМЕЕТ обозначенное), обобщается на новые входы и КОМПОНУЕТСЯ")
    print("   в новые предложения. Это разбор→вывод→исполнение, а не генерация правдоподобного.")
    print("   Узко и честно: контролируемый словарь, без морфологии — но это НАСТОЯЩИЙ смысл,")
    print("   первый камень моста «язык → мышление». Дальше — факты→вывод и причинные утверждения.")


if __name__ == "__main__":
    main()
