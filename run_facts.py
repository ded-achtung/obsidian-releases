#!/usr/bin/env python3
"""Понимание утверждений: язык → факты → ВЫВОД (отвечает дедукцией, не генерацией).

Система разбирает утверждения в факты, строит их следствия (транзитивность,
наследование) и отвечает на вопросы дедукцией — в том числе на то, что прямо не
говорилось. «Сократ смертен» не сказано, но СЛЕДУЕТ из понятых посылок.

Запуск: python run_facts.py
"""

from __future__ import annotations

from thinking_system.language.facts import FactReader


def main():
    print("▶ Мост «язык → смысл»: понимание утверждений и ответ ВЫВОДОМ\n")
    fr = FactReader()

    statements = [
        "Сократ это человек",
        "человек это млекопитающее",
        "млекопитающее это животное",
        "каждый человек смертный",
        "каждое животное дышит",
    ]
    print("1) ПОНЯЛ УТВЕРЖДЕНИЯ → факты:")
    for s in statements:
        rel, a, b = fr.tell(s)
        print(f"   «{s:<28}» → {rel}({a}, {b})")

    print("\n2) ОТВЕЧАЕТ ВЫВОДОМ (ничего из этого не говорилось прямо):")
    for q in ["Сократ это животное?", "Сократ смертный?", "Сократ дышит?", "человек это животное?"]:
        print(f"   {q:<26} → {fr.answer(q)}")

    print("\n3) ЧЕСТНО про невыводимое (генератор выдумал бы «да»):")
    print(f"   Сократ летает?             → {fr.answer('Сократ летает?')}")

    print("\n── Что это значит ──")
    print("   Система ПОНЯЛА посылки (построила их инференциальные следствия) и ВЫВЕЛА")
    print("   «Сократ смертен», «Сократ — животное», «Сократ дышит» — хотя это не звучало.")
    print("   Это разбор → дедукция → истинный ответ (или честное «нет»), а не генерация.")
    print("   Второй камень моста «язык → мышление»: смысл утверждения = что из него следует.")


if __name__ == "__main__":
    main()
