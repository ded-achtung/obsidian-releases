#!/usr/bin/env python3
"""Морфология: понимать менее «причёсанный» текст (формы слова → общая основа).

Лёгкий стеммер (по правилам, без корпуса) приводит формы слова к основе, чтобы
разные формы узнавались как одно: «наибольший / наибольшее / наибольшие» → одно
правило. Тогда система понимает задачи в разных формулировках, а не только в
точной форме из учебника.

Запуск: python run_morphology.py
"""

from __future__ import annotations

from thinking_system.language.study import Textbook
from thinking_system.language.morphology import stem

BOOK = """
Пример: максимум [3,1,2] = 3
Пример: максимум [5,9,2] = 9
Пример: сумма [1,2,3] = 6
Пример: сумма [4,5] = 9
максимум нужен когда просят наибольший
сумма нужна когда просят общий итог
"""


def main():
    print("▶ Морфология: формы слова → основа, чтобы понимать разные формулировки\n")

    print("1) СТЕММЕР приводит формы к одной основе (правила, без данных):")
    for forms in [["наибольший", "наибольшее", "наибольшие", "наибольшего"],
                  ["сумма", "сумму", "суммой", "суммы"],
                  ["отрицательный", "отрицательные", "отрицательными"]]:
        print(f"   {forms} → «{stem(forms[0])}»  ({'все совпали' if len({stem(w) for w in forms}) == 1 else 'разошлись'})")

    tasks = ["найди наибольшее [4, 2, 9, 1]", "наибольший элемент [7, 3, 8]", "посчитай общую сумму [10, 20, 30]"]

    print("\n2) БЕЗ морфологии (узнаёт только точную форму из учебника):")
    plain = Textbook()
    plain.study(BOOK)
    for t in tasks:
        r = plain.solve(t)
        print(f"   «{t:<30}» → {r.get('answer', r.get('reason'))}")

    print("\n3) С морфологией (формы → основа — понимает разные формулировки):")
    rob = Textbook(normalize=stem)
    rob.study(BOOK)
    for t in tasks:
        r = rob.solve(t)
        print(f"   «{t:<30}» → {r.get('answer', r.get('reason'))}   ⟵ {' ▸ '.join(r.get('used', []))}")

    print("\n── Что это значит ──")
    print("   Та же система, но формы слова сводятся к основе — и она узнаёт правило в РАЗНЫХ")
    print("   формулировках («наибольшее», «наибольший»), а не только в точной форме учебника.")
    print("   Честно: стеммер по правилам ловит словоизменение (падежи/числа), но не видовые")
    print("   пары и словообразование — для них нужен словарь. Шаг к менее причёсанному тексту.")


if __name__ == "__main__":
    main()
