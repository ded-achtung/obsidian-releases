#!/usr/bin/env python3
"""Учёба по учебнику: выучить правила И когда их применять, решать задачи по смыслу.

Система читает учебник из трёх частей: ПРИМЕРЫ (что делает операция), ТЕОРИЯ
(когда применять — по каким приметам задачи) и ЗАДАЧИ. В задачах операция НЕ
названа — система сама ВЫБИРАЕТ правило по смыслу задачи и исполняет.

Запуск: python run_study.py
"""

from __future__ import annotations

from thinking_system.language.study import Textbook
from thinking_system.text.ingest import load_book


def main():
    print("▶ Учёба по учебнику: выучить операции, теорию применимости и решать задачи\n")
    tb = Textbook()
    stats = tb.study(load_book("books/textbook_lists.md"))

    print(f"1) ПРОШТУДИРОВАЛ учебник: {stats['операции']} операции, {stats['приметы']} примет применимости, {stats['задачи']} задачи")
    print(f"   ЧТО ДЕЛАЮТ (из примеров): {', '.join(f'{w}={p}' for w, p in tb.lex.words.items())}")
    print("   КОГДА ПРИМЕНЯТЬ (из теории):")
    by_op: dict[str, list[str]] = {}
    for cue, op in tb.applicability.items():
        by_op.setdefault(op, []).append(cue)
    for op, cues in by_op.items():
        print(f"     {op} ← по словам: {', '.join(cues)}")

    print("\n2) РЕШАЕТ ЗАДАЧИ, ВЫБИРАЯ ПРАВИЛО ПО СМЫСЛУ (операция в задаче НЕ названа):")
    for r in tb.solve_exercises():
        print(f"   «{r['задача']:<28}» → {r['answer']}   ⟵ применил правило: {' ▸ '.join(r['used'])}")

    print("\n3) ЧЕСТНО, когда правило не подобрать:")
    r = tb.solve("посчитай среднее [1, 2, 3]")
    print(f"   «посчитай среднее [1,2,3]» → {r['reason']} («среднее» в учебнике не объяснено)")

    print("\n── Что это значит ──")
    print("   Система выучила ИЗ УЧЕБНИКА и ЧТО делают операции (из примеров), и КОГДА их")
    print("   применять (из теории), и решает задачи, САМА подбирая правило по смыслу —")
    print("   хотя операция в условии не названа. Это знание + применимость: не только")
    print("   уметь делать, но и понимать, когда это нужно. Честно: контролируемый текст,")
    print("   подбор по словам-приметам, без морфологии — но это реальный перенос знания.")


if __name__ == "__main__":
    main()
