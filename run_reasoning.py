#!/usr/bin/env python3
"""Рассуждение из 2-3 примеров: индукция правил поиском, без корпуса.

Система выводит ПРАВИЛО из пары примеров вход→выход (поиск кратчайшей программы в
маленьком языке операций) и применяет к новым входам — обобщает на бесконечно много
случаев. Сравнение со статистическим обучением, рост рассуждения через абстракции
и честные границы (язык + глубина поиска).

Запуск: python run_reasoning.py
"""

from __future__ import annotations

from thinking_system.reasoning.induction import default_library


def main():
    print("▶ Индукция правил: учимся из 2-3 примеров ПОИСКОМ программы (без корпуса)\n")

    # 1) few-shot: правило из 2 примеров → обобщение на невиданные входы
    print("1) ИЗ 2-3 ПРИМЕРОВ — выводит правило и обобщает на НОВЫЕ входы:")
    tasks = [
        ("x²",            [(3, 9), (4, 16)],                       [(7, 49), (10, 100), (11, 121)]),
        ("x·2+1",         [(3, 7), (5, 11)],                       [(10, 21), (100, 201)]),
        ("(x+1)²",        [(2, 9), (3, 16)],                       [(5, 36), (9, 100)]),
        ("развернуть",    [([1, 2, 3], [3, 2, 1]), ([4, 5], [5, 4])], [([7, 8, 9], [9, 8, 7]), ([2, 3, 4, 5], [5, 4, 3, 2])]),
        ("сумма удвоенных", [([1, 2, 3], 12), ([5], 10)],          [([10], 20), ([1, 1, 1, 1], 8)]),
        ("максимум",      [([3, 1, 2], 3), ([5, 9, 2], 9)],        [([8, 1], 8), ([4, 4, 7], 7)]),
    ]
    for name, ex, test in tasks:
        prog = default_library().induce(ex, max_depth=3)
        gen = sum(prog(i) == o for i, o in test) / len(test) if prog else 0.0
        rule = f"«{prog}»" if prog else "—"
        print(f"   {name:<16} из {len(ex)} прим. → правило {rule:<22} обобщение на новых: {gen:.0%}")

    # 2) контраст со статистическим обучением (из тех же 2 примеров)
    print("\n2) ПОЧЕМУ НЕ СТАТИСТИКА — то же из 2 примеров, проверка на новых входах:")
    prog = default_library().induce([(3, 9), (4, 16)], max_depth=2)         # x²
    tests = [7, 10, 11]
    # линейная экстраполяция по 2 точкам (3,9),(4,16): y = 7x - 12
    sl = (16 - 9) / (4 - 3); itc = 9 - sl * 3
    ind = [prog(x) for x in tests]; lin = [int(sl * x + itc) for x in tests]; true = [x * x for x in tests]
    print(f"   задача x²; входы {tests}, истина {true}")
    print(f"   индукция правила:        {ind}   ✓ выводит x² и обобщает точно")
    print(f"   линейная подгонка 2 точек:{lin}   ✗ интерполирует, но правило не то")
    rev = default_library().induce([([1, 2, 3], [3, 2, 1])], max_depth=1)   # reverse из ОДНОГО примера
    memo = {(1, 2, 3): [3, 2, 1]}
    new = [4, 5, 6]
    print(f"   задача «развернуть»; новый вход {new}: правило → {rev(new)} ✓ ;  запоминание примеров → "
          f"{memo.get(tuple(new), 'нет ответа')} ✗")

    # 3) рассуждение УЛУЧШАЕТСЯ с опытом: абстракция сокращает поиск
    print("\n3) РОСТ РАССУЖДЕНИЯ — решённое становится примитивом (абстракция):")
    lib = default_library()
    hard = [(2, 18), (3, 32)]                                                # ((x+1)²)·2 — глубина 3
    print(f"   сложная задача ((x+1)²·2) при глубине поиска 2: {lib.induce(hard, max_depth=2)}  (вне досягаемости)")
    sub = lib.induce([(2, 9), (3, 16)], max_depth=2)                         # выучить (x+1)²
    lib.add_abstraction("inc_sq", sub)
    sol = lib.induce(hard, max_depth=2)
    print(f"   выучили абстракцию inc_sq=(x+1)²; теперь та же задача при глубине 2: «{sol}» ✓")
    print(f"   и обобщает: вход 10 → {sol(10)} (истина {((10 + 1) ** 2) * 2})")

    # 4) честные границы
    print("\n4) ЧЕСТНЫЕ ГРАНИЦЫ — сила ограничена ЯЗЫКОМ (приорами):")
    print(f"   x³ при отсутствии куба в языке: {default_library().induce([(2, 8), (3, 27)], max_depth=3)} "
          f"(нет нужного примитива — не выведет; поиск растёт экспоненциально с глубиной)")

    print("\n── Итог ──")
    print("   Это рассуждение, а не подгонка: из 2-3 примеров система ИЩЕТ правило и точно")
    print("   обобщает на новое — без корпуса. Статистика так из малого не может. Абстракции")
    print("   делают рассуждение глубже со временем. Цена честна: нужен правильный язык и")
    print("   поиск дорог — но это и есть путь «учиться многому из малого».")


if __name__ == "__main__":
    main()
