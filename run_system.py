#!/usr/bin/env python3
"""ЕДИНАЯ думающая система: ОДИН агент, ОДНА память, переносы между факультетами.

Раньше каждая способность была отдельной демкой. Здесь — один объект
`ThinkingSystem`, который ЧИТАЕТ, ОТВЕЧАЕТ дедукцией, РЕШАЕТ задачи поиском,
ИМЕНУЕТ найденные навыки (и тогда ими владеет язык), ВОСПРИНИМАЕТ потоки
любопытством и ДЕЙСТВУЕТ в мире — всё в общей памяти, переживающей между шагами.

Ключевое (то, что делает это ОДНОЙ системой, а не набором демок):
  • навык, выученный ЧТЕНИЕМ, попадает в общую библиотеку и доступен РАССУЖДЕНИЮ;
  • программа, найденная ПОИСКОМ, после name_skill становится СЛОВОМ ЯЗЫКА и
    сокращает будущий поиск (глубина 2 → 1) — рост словаря замыкается в кольцо;
  • факты и причины из ЧТЕНИЯ отвечают на ВОПРОСЫ дедукцией по той же памяти.

Запуск: python run_system.py
"""

from __future__ import annotations

from thinking_system import ThinkingSystem

BOOK = """
# учебник для единой системы
Пример: разверни [1, 2, 3] = [3, 2, 1]
Пример: разверни [4, 5] = [5, 4]
Пример: удвой [1, 2, 3] = [2, 4, 6]
Пример: удвой [5, 1] = [10, 2]
Пример: сумма [1, 2, 3] = 6
Пример: сумма [4, 5] = 9
Сократ это человек.
человек это млекопитающее.
млекопитающее это животное.
каждый человек смертный.
дождь вызывает мокрый.
мокрый вызывает скользкий.
просто повествование без структуры
"""

RU = ("Система читает текст и предсказывает следующий байт. "
      "Та же ошибка предсказания учит модель и ведёт внимание. ") * 12
CODE = ("def add(a, b):\n    return a + b  # сложение\n"
        "def mul(a, b):\n    return a * b  # умножение\n") * 12


def main() -> None:
    ts = ThinkingSystem(seed=0)
    print("▶ ЕДИНАЯ думающая система: один агент со общей памятью\n")

    # 1) ЧТЕНИЕ → слова + факты + причины в общую память
    r = ts.read(BOOK)
    s = r["stats"]
    print("① ЧТЕНИЕ книги (одна память на всё):")
    print(f"   выучено: {s['слова']} слов-операций, {s['факты']} фактов, {s['причины']} причинных связей "
          f"({s['пропущено']} строк прозы честно пропущено)")
    print(f"   эти слова сразу вошли в общую библиотеку рассуждения: {r['learned_words']}")

    # 2) ВОПРОСЫ → дедукция по прочитанному (то, что прямо не сказано)
    print("\n② ВОПРОСЫ — ответ ДЕДУКЦИЕЙ по прочитанному (не сказано прямо):")
    for q in ["Сократ это животное?", "Сократ смертный?",
              "если включить дождь, будет скользкий?", "Сократ летает?"]:
        print(f"   «{q}» → {ts.ask(q)}")

    # 3) ЯЗЫК — композиция ПРОЧИТАННЫХ слов и исполнение
    print("\n③ ЯЗЫК — понять предложение из читанных слов и ИСПОЛНИТЬ:")
    u = ts.understand("удвой и сумма [1, 2, 3]")
    print(f"   «удвой и сумма [1,2,3]» → {u['answer']}   (составлено: {u['reasoning']})")

    # 4) ПЕРЕНОС рассуждение→язык: найти навык поиском и НАЗВАТЬ
    print("\n④ РАССУЖДЕНИЕ → ЯЗЫК — найти навык поиском и назвать (рост словаря):")
    before = ts.solve([(2, 5), (3, 10)], max_depth=1, invent=False)
    ts.name_skill("квадрик", [(2, 5), (3, 10)])           # x² + 1
    after = ts.solve([(2, 5), (3, 10)], max_depth=1, invent=False)
    print(f"   x²+1 на глубине 1 ДО имени: {before};  ПОСЛЕ name_skill: «{after}»")
    print(f"   теперь это и СЛОВО языка: «квадрик 4» → {ts.understand('квадрик 4')['answer']}")

    # 4′) ИЗОБРЕТЕНИЕ операции ИЗ НАБЛЮДАЕМОГО (когда композиция известного не подходит)
    print("\n④′ ИЗОБРЕТЕНИЕ операции из НАБЛЮДАЕМОГО (не из воздуха — из регулярности):")
    quad = [(2, 6), (3, 12), (4, 20), (5, 30)]                # x²+x
    no = ts.solve(quad, invent=False)                         # композиции seed нет
    inv = ts.solve(quad)                                      # выводим из 4 наблюдений (4-я подтверждает)
    print(f"   x²+x композицией seed: {no};  выведено из 4 наблюдений: «{inv}», новый вход 6 → {inv(6)}")
    # свежей системе (без уже выученного) из 3 точек квадратичную не подтвердить — честно None
    print(f"   честная граница (подтверждение, а не подгонка): свежей системе 3 точек мало → "
          f"{ThinkingSystem().solve([(2, 6), (3, 12), (4, 20)])}")

    # 4″) СЛЕДУЮЩИЙ СЛОЙ: УСЛОВИЕ и ВЕТВЛЕНИЕ из наблюдений (предикат + if/else из данных)
    print("\n④″ УСЛОВИЕ И ВЕТВЛЕНИЕ из наблюдений (предикат и if/else выведены из данных):")
    pred = ts.learn_predicate([([1, 2], True), ([1, -1], False), ([3, 4], True), ([0, 5], False)])
    print(f"   выучен ПРЕДИКАТ из примеров «вход → да/нет» (не захардкожен): «{pred}»")
    absf = ts.solve([(-3, 3), (-2, 2), (-5, 5), (1, 1), (4, 4), (6, 6)])     # модуль
    print(f"   модуль выведен ветвлением: «{absf}», новый вход -7 → {absf(-7)}")
    dbl = ts.solve([(2, 4), (4, 8), (6, 12), (3, 3), (5, 5), (7, 7)])        # удвоить чётные
    print(f"   удвоить чётные, нечётные оставить: «{dbl}», 8 → {dbl(8)}, 7 → {dbl(7)}")
    print(f"   честная граница: 4 произвольные точки ветвлением не объяснить → "
          f"{ts.solve([(1, 5), (2, 9), (3, 2), (4, 7)])}")

    # 4‴) СТРУКТУРНЫЕ операции над списками + МНОГОВЕТОЧНОЕ условие (из наблюдений)
    print("\n④‴ СТРУКТУРА списков и МНОГОВЕТОЧНОЕ условие (позиция/период/N ветвей):")
    rot = ts.solve([([1, 2, 3], [2, 3, 1]), ([4, 5, 6, 7], [5, 6, 7, 4])])     # сдвиг по позиции
    print(f"   циклический сдвиг (по позиции, ≥2 длин): «{rot}», [9,8] → {rot([9, 8])}")
    rep = ts.solve([([1, 2], [1, 2, 1, 2]), ([3, 4, 5], [3, 4, 5, 3, 4, 5])])  # период
    print(f"   повтор/период: «{rep}», [7] → {rep([7])}")
    sign = ts.solve([(-3, -1), (-2, -1), (5, 1), (7, 1), (0, 0)])              # 3 ветви
    print(f"   знак числа (3 ветви из данных): «{sign}», -9 → {sign(-9)}, 4 → {sign(4)}, 0 → {sign(0)}")
    print(f"   честная граница: сдвиг на ОДНОЙ длине не подтверждён → "
          f"{ThinkingSystem().solve([([1, 2, 3], [2, 3, 1]), ([4, 5, 6], [5, 6, 4])])}")

    # 4⁗) СКОЛЬЗЯЩЕЕ ОКНО, СЕТКИ и ВЛОЖЕННЫЕ правила (из наблюдений)
    print("\n④⁗ ОКНО/свёртка, СЕТКИ и ВЛОЖЕННЫЕ правила (из наблюдений):")
    dff = ts.solve([([1, 3, 6, 10], [2, 3, 4]), ([2, 5, 9], [3, 4])])          # разности (свёртка)
    print(f"   разности соседей: «{dff}», [10,12,20] → {dff([10, 12, 20])}")
    grd = ts.solve([([[1, 2], [3, 4]], [[2, 1], [4, 3]]),
                    ([[5, 6], [7, 8]], [[6, 5], [8, 7]])])                      # сетка: подбор grid-операции
    print(f"   преобразование сетки (подбор по grid-примитивам): «{grd}», [[9,0],[1,2]] → {grd(((9, 0), (1, 2)))}")
    nst = ts.solve([([1, 2], [1, 2]), ([2, 1], [2, 1]), ([1, 2, 3], [3, 2, 1]),
                    ([3, 2, 1], [1, 2, 3]), ([2, 4, 6, 8], [8, 6, 4, 2]), ([1, 3], [1, 3])])
    print(f"   ВЛОЖЕННОЕ (структура в ветке под выученным условием): «{nst}», [5,6,7] → {nst([5, 6, 7])}")

    # ★ 2D-сетки (перекраска/морфология) и ГЛУБОКОЕ дерево решений (из наблюдений)
    print("\n★ 2D-сетки (перекраска/морфология) и ГЛУБОКОЕ дерево решений:")
    sw = ts.solve([([[1, 2, 1]], [[2, 1, 2]]), ([[2, 2, 1]], [[1, 1, 2]])])     # обмен цветов 1↔2
    print(f"   перекраска цветов 1↔2: «{sw}», [[1,1,2,2]] → {sw(((1, 1, 2, 2),))}")
    G = ((0, 0, 0), (0, 5, 0), (0, 0, 0))
    dil = ts.solve([(G, ((0, 5, 0), (5, 5, 5), (0, 5, 0))), (((0, 0), (3, 0)), ((3, 0), (3, 3)))])
    print(f"   2D-морфология (дилатация по соседству): «{dil}», точка 5 → {dil(G)}")
    clf = lambda x: 0 if x < 0 else (10 if x > 10 else x)
    cl = ts.solve([(-5, 0), (-2, 0), (3, 3), (7, 7), (8, 8), (9, 9), (11, 10), (15, 10)])
    print(f"   ограничение в [0,10] (дерево решений): «{cl}», -9→{cl(-9)}, 5→{cl(5)}, 20→{cl(20)}")
    st = ts.solve([(-3, -1), (-1, -1), (0, 0), (2, 1), (5, 1), (6, 2), (9, 2)])  # 4 региона (глубина 2)
    print(f"   4 региона (вложенность глубже): «{st}», 5→{st(5)}, 6→{st(6)}")

    # 5) ВОСПРИЯТИЕ потоков — предсказание + любопытство + эпизодическая память
    print("\n⑤ ВОСПРИЯТИЕ байтовых потоков (тот же кортекс, общая память):")
    p = ts.perceive([("рус-текст", RU), ("python-код", CODE)], steps=4000)
    for name, b0, b1 in zip(p["names"], p["bpc_before"], p["bpc_after"]):
        print(f"   {name:<12} bits/byte {b0:.2f} → {b1:.2f}")

    # 6) ДЕЙСТВИЕ в мире — та же связка предсказание+активный вывод+память
    print("\n⑥ ДЕЙСТВИЕ в незнакомом мире (модель мира + активный вывод):")
    w = ts.learn_world(episodes=40)
    a = ts.act()
    print(f"   путь к цели: {w['steps_first']} → {a['steps']} шагов (оптимум {w['optimal']}), дошёл: {a['reached']}")

    # 7) ЕДИНОЕ СОСТОЯНИЕ — всё нажитое в ОДНОМ объекте
    print("\n⑦ СОСТОЯНИЕ УМА (всё — в одном объекте, переживает между вызовами):")
    for k, v in ts.mind().items():
        print(f"   {k}: {v}")

    print("\n── Что это значит ──")
    print("   Это не шесть демок рядом, а ОДИН агент: чтение, дедукция, синтез программ,")
    print("   именование навыков, восприятие потоков и действие в мире делят общую память")
    print("   и язык. Навык, открытый поиском, становится словом; прочитанное отвечает на")
    print("   вопросы; та же ошибка предсказания учит, ведёт внимание и переносится на действие.")


if __name__ == "__main__":
    main()
