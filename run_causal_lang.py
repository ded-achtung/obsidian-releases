#!/usr/bin/env python3
"""Понимание причинных утверждений: язык → причинная модель → вмешательства/«что если».

Система разбирает «X вызывает Y» в причинный граф, строит модель и отвечает
рассуждением: причинно ли влияет, что будет если СДЕЛАТЬ (do), различает «видеть»
(корреляция) от «делать» (причинность) и считает контрфактику. Думать по модели,
а не генерировать.

Запуск: python run_causal_lang.py
"""

from __future__ import annotations

from thinking_system.language.causal_lang import CausalReader


def main():
    print("▶ Мост «язык → смысл»: понимание ПРИЧИННЫХ утверждений\n")
    cr = CausalReader()

    claims = ["дождь вызывает мокрый", "спринклер вызывает мокрый",
              "мокрый вызывает скользкий", "дождь вызывает холодный"]
    print("1) ПОНЯЛ ПРИЧИННЫЕ УТВЕРЖДЕНИЯ → граф:")
    for s in claims:
        x, y = cr.tell(s)
        print(f"   «{s:<26}» → {x} → {y}")

    print("\n2) ПРИЧИННОСТЬ (есть ли путь воздействия):")
    for q in ["спринклер вызывает скользкий?", "дождь вызывает скользкий?", "спринклер вызывает дождь?"]:
        print(f"   {q:<30} → {cr.answer(q)}")

    print("\n3) КОРРЕЛЯЦИЯ ≠ ПРИЧИННОСТЬ («мокрый» и «холодный» — общий предок «дождь»):")
    print(f"   мокрый ВЫЗЫВАЕТ холодный?  → {'да' if cr.causes('мокрый', 'холодный') else 'нет'}  (причинного пути нет)")
    print(f"   мокрый СВЯЗАН с холодный?  → {'да' if cr.correlated('мокрый', 'холодный') else 'нет'}  (видеть мокрый — ожидать холодный)")

    print("\n4) ВМЕШАТЕЛЬСТВО (если СДЕЛАТЬ):")
    for q in ["если включить спринклер, будет скользкий?", "если включить спринклер, будет дождь?"]:
        print(f"   {q:<44} → {cr.answer(q)}")

    print("\n5) КОНТРФАКТИКА (наблюдали: спринклер вкл, дождя нет, мокро, скользко):")
    ev = {"спринклер": 1, "дождь": 0, "мокрый": 1, "скользкий": 1, "холодный": 0}
    cf = cr.counterfactual(ev, {"спринклер": 0}, "мокрый")
    print(f"   «если бы спринклер не работал, было бы мокро?» → {'нет' if cf.get(0) == 1.0 else 'да'}  (спринклер БЫЛ причиной)")

    print("\n── Что это значит ──")
    print("   Из причинных утверждений система ПОСТРОИЛА модель и рассуждает: отличает")
    print("   «видеть» от «делать», отвечает на «если сделать», считает «что было бы».")
    print("   Это разбор → причинная модель → вывод, а не генерация. Третий камень моста.")


if __name__ == "__main__":
    main()
