#!/usr/bin/env python3
"""Учиться по книге со СМЫСЛОМ: прочитать урок из файла → понять → использовать.

Система сканирует текст и сама извлекает разнотипный материал: проработанные
примеры «вход→выход» (учит значения слов), факты (база знаний), причинные связи
(причинная модель). Повествование честно пропускает. Затем ИСПОЛЬЗУЕТ прочитанное:
решает задачи, отвечает дедукцией, рассуждает о причинах.

Запуск: python run_read_book.py
"""

from __future__ import annotations

from thinking_system.language.reader import LessonReader


def main():
    print("▶ Чтение СМЫСЛА из текста: книга → понимание → использование\n")
    reader = LessonReader()
    stats = reader.read_file("books/sample_lesson.md")

    print("1) ПРОЧИТАЛ урок books/sample_lesson.md и извлёк смысл по типам:")
    print(f"   проработанных примеров: {stats['примеры']} → выучено слов-операций: {stats['слова']}")
    print(f"   фактов: {stats['факты']}   причинных связей: {stats['причины']}   пропущено прозы: {stats['пропущено']}")
    print(f"   значения слов (выведены из примеров в тексте): {', '.join(f'{w}={p}' for w, p in reader.lex.words.items())}")

    print("\n2) ИСПОЛЬЗУЕТ выученные ИЗ ТЕКСТА операции (новые входы, композиция):")
    for task in ["разверни [9,8,7]", "удвой [4,5]", "удвой и сумма [1,2,3]"]:
        r = reader.solve(task)
        print(f"   «{task:<22}» → {r['answer']}   (понял как: {r['reasoning']})")

    print("\n3) ОТВЕЧАЕТ ВЫВОДОМ по фактам ИЗ ТЕКСТА (не было сказано прямо):")
    for q in ["Сократ это животное?", "Сократ смертный?", "Сократ дышит?"]:
        print(f"   {q:<24} → {reader.ask_fact(q)}")

    print("\n4) РАССУЖДАЕТ О ПРИЧИНАХ по связям ИЗ ТЕКСТА:")
    for q in ["если включить спринклер, будет скользкий?", "спринклер вызывает дождь?"]:
        print(f"   {q:<44} → {reader.ask_causal(q)}")

    print("\n── Что это значит ──")
    print("   Система ПРОЧИТАЛА смешанный материал из файла, извлекла смысл трёх типов и")
    print("   стала им пользоваться: решает задачи словами из текста, выводит факты, которых")
    print("   не было прямо, рассуждает о причинах. Это «учиться по книге со смыслом» —")
    print("   разбор→понимание→использование, а не статистическое подражание тексту.")
    print("   Честно: контролируемый текст и разбор по образцам, не полный NLP — но это")
    print("   реальное понимание прочитанного, и его можно расширять.")


if __name__ == "__main__":
    main()
